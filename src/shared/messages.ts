export type Language = 'en' | 'hu'
export type Message = keyof typeof hungarian
type Values = Readonly<Record<string, string | number>>
export type Translate = (message: Message, values?: Values) => string

const languageKey = 'lighthouse-language'

export function readLanguage(): Language {
  return localStorage.getItem(languageKey) === 'hu' ? 'hu' : 'en'
}

export function writeLanguage(language: Language) {
  localStorage.setItem(languageKey, language)
}

export function isLanguageChange(event: StorageEvent) {
  return event.storageArea === localStorage && (event.key === languageKey || event.key === null)
}

export function translate(language: Language, message: Message, values?: Values): string {
  const text = language === 'hu' ? hungarian[message] : message
  return values ? text.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match)) : text
}

export function translateError(t: Translate, original: string): string {
  const error = original.startsWith('Error: ') ? original.slice(7) : original
  if (Object.hasOwn(hungarian, error)) return t(error as Message)
  for (const [prefix, message] of [
    ['Could not open the workspace: ', 'Could not open the workspace: {detail}'],
    ['Could not save changes: ', 'Could not save changes: {detail}'],
    ['Invalid Bible JSON file. ', 'Invalid Bible JSON file. {detail}'],
  ] as const) {
    if (error.startsWith(prefix)) {
      return t(message, { detail: translateError(t, error.slice(prefix.length)) })
    }
  }
  return original
}
